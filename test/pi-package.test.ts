describe("mu pi migrate", () => {
  let home: string;
  const ext = () => join(home, ".pi", "agent", "extensions", "mu.ts");
  const skill = () => join(home, ".agents", "skills", "mu");
  // The real template every released 3.x `mu link pi` wrote (v3.2.0..v3.13.3
  // are byte-identical), generated by the old src/link.ts for /opt/mu.
  const template = readFileSync(join(root, "test", "fixtures", "link-shim-v3.txt"), "utf8");
  const entry = "file:///x/node_modules/@mu-crew/mu/dist/extension/mu-pi.js";
  const shim = template.replace("file:///opt/mu/dist/extension/mu-pi.js", entry);
  const pkgRoot = () => join(home, "pkg");

  beforeEach(() => {
    home = mkdtempSync(join(tmpdir(), "mu-migrate-"));
  });
  afterEach(() => rmSync(home, { recursive: true, force: true }));

  function putShim(): void {
    mkdirSync(join(home, ".pi", "agent", "extensions"), { recursive: true });
    writeFileSync(ext(), shim);
  }
  function putSkillLink(under = "pkg"): string {
    const target = join(home, under, "skills", "mu");
    mkdirSync(target, { recursive: true });
    writeFileSync(join(target, "SKILL.md"), "---\nname: mu\n---\n");
    mkdirSync(join(home, ".agents", "skills"), { recursive: true });
    symlinkSync(target, skill(), "dir");
    return target;
  }

  it("reports and changes nothing without apply", () => {
    putShim();
    const r = migratePi({ home });
    expect(r.extension.state).toBe("shim");
    expect(r.extension.moved).toBe(false);
    expect(existsSync(ext())).toBe(true);
  });

  it("moves the verified shim out of discovery, to a name pi never loads", () => {
    putShim();
    const r = migratePi({ home, apply: true });
    expect(r.extension.moved).toBe(true);
    expect(existsSync(ext())).toBe(false);
    const to = r.extension.to ?? "";
    expect(to).toContain(join(home, ".pi", "agent"));
    expect(to.endsWith(".ts")).toBe(false);
    expect(readFileSync(to, "utf8")).toBe(shim);
    expect(r.guidance.join(" ")).toMatch(/restart|\/reload/);
  });

  it("moves a mu skill symlink and leaves its target alone", () => {
    const target = putSkillLink();
    const r = migratePi({ home, apply: true, packageRoot: pkgRoot() });
    expect(r.skill.moved).toBe(true);
    expect(existsSync(skill())).toBe(false);
    expect(existsSync(join(target, "SKILL.md"))).toBe(true);
  });

  it("never touches a copy, a real directory or a foreign symlink", () => {
    mkdirSync(join(home, ".pi", "agent", "extensions"), { recursive: true });
    writeFileSync(ext(), "export default function () {}\n");
    putSkillLink("elsewhere");
    const r = migratePi({ home, apply: true, packageRoot: pkgRoot() });
    expect(r.extension).toMatchObject({ state: "foreign", moved: false });
    expect(r.skill).toMatchObject({ state: "foreign", moved: false });
    expect(readFileSync(ext(), "utf8")).toContain("export default");
    expect(lstatSync(skill()).isSymbolicLink()).toBe(true);

    rmSync(skill());
    mkdirSync(skill(), { recursive: true });
    expect(migratePi({ home, apply: true, packageRoot: pkgRoot() }).skill).toMatchObject({
      state: "foreign",
      moved: false,
    });
    expect(existsSync(skill())).toBe(true);
  });

  describe("ownership is proven, never inferred from a marker", () => {
    function putExt(body: string): void {
      mkdirSync(join(home, ".pi", "agent", "extensions"), { recursive: true });
      writeFileSync(ext(), body);
    }

    it("leaves a user extension that merely mentions the marker", () => {
      const body = `// My personal extension, not generated by mu.\nconst historicalMarker = "${MU_SHIM_MARKER}";\nexport default function () {}\n`;
      putExt(body);
      const r = migratePi({ home, apply: true });
      expect(r.extension).toMatchObject({ state: "foreign", moved: false });
      expect(readFileSync(ext(), "utf8")).toBe(body);
      expect(r.guidance.join(" ")).toContain(ext());
    });

    it("the checked-in template is itself recognised", () => {
      expect(isMuShimText(template)).toBe(true);
    });

    it("leaves the reviewer's file: marker line plus a commented import", () => {
      const body = `${MU_SHIM_MARKER}\n// Historical example only: await import("${entry}");\nexport default function personalExtension(pi) { pi.registerCommand("personal", { description: "User command", handler: async () => {} }); }\n`;
      putExt(body);
      const r = migratePi({ home, apply: true });
      expect(r.extension).toMatchObject({ state: "foreign", moved: false });
      expect(readFileSync(ext(), "utf8")).toBe(body);
      expect(existsSync(join(home, ".pi", "agent", "disabled"))).toBe(false);
    });

    it("leaves a marker first line that does not import mu's built extension", () => {
      putExt(`${MU_SHIM_MARKER}\nexport default function () {}\n`);
      expect(migratePi({ home, apply: true }).extension).toMatchObject({
        state: "foreign",
        moved: false,
      });
      putExt(`// mine\n${MU_SHIM_MARKER}\nawait import("${entry}");\n`);
      expect(migratePi({ home, apply: true }).extension.moved).toBe(false);
    });

    it("moves the exact template with another generated install path", () => {
      putExt(shim.replace("/x/node_modules", "/opt/other/place"));
      expect(migratePi({ home, apply: true }).extension.moved).toBe(true);
    });

    it.each([
      ["a changed comment", (t: string) => t.replace("Do not edit.", "Edit freely.")],
      ["a trailing line", (t: string) => `${t}console.log("hi");\n`],
      ["a missing final newline", (t: string) => t.trimEnd()],
      ["CRLF line endings", (t: string) => t.replace(/\n/g, "\r\n")],
      ["a leading line", (t: string) => `// mine\n${t}`],
      ["a changed export", (t: string) => t.replace("export default extension;", "export {};")],
      [
        "a commented-out generated import",
        (t: string) => t.replace("await import(", "// await import("),
      ],
      [
        "a single-quoted import",
        (t: string) => t.replace(/"file:[^"]*"/, "'file:///opt/mu/dist/extension/mu-pi.js'"),
      ],
      ["a relative import", (t: string) => t.replace(/"file:[^"]*"/, '"./mu-pi.js"')],
      ["another file", (t: string) => t.replace("mu-pi.js", "personal.js")],
      ["a non-canonical URL", (t: string) => t.replace("file:///opt/mu", "file:///opt/../opt/mu")],
      [
        "an import with a second argument",
        (t: string) =>
          t.replace(/\("file:[^"]*"\)/, '("file:///opt/mu/dist/extension/mu-pi.js", {})'),
      ],
      [
        "a second import after the first",
        (t: string) =>
          t.replace(
            /\("file:[^"]*"\)/,
            '("file:///opt/mu/dist/extension/mu-pi.js"); await import("file:///x/other.js"',
          ),
      ],
    ])("leaves a near-copy of the template: %s", (_name, mutate) => {
      const body = mutate(template);
      expect(body).not.toBe(template);
      putExt(body);
      const r = migratePi({ home, apply: true });
      expect(r.extension).toMatchObject({ state: "foreign", moved: false });
      expect(readFileSync(ext(), "utf8")).toBe(body);
    });

    it("leaves a skill link to a custom skill that is merely named mu", () => {
      const target = join(home, "personal-skills", "mu");
      mkdirSync(target, { recursive: true });
      writeFileSync(join(target, "SKILL.md"), "---\nname: mu\ndescription: mine\n---\n");
      mkdirSync(join(home, ".agents", "skills"), { recursive: true });
      symlinkSync(target, skill(), "dir");
      const r = migratePi({ home, apply: true, packageRoot: pkgRoot() });
      expect(r.skill).toMatchObject({ state: "foreign", moved: false });
      expect(lstatSync(skill()).isSymbolicLink()).toBe(true);
      expect(r.guidance.join(" ")).toContain(skill());
    });

    it("moves a symlink that resolves into this install's skills/mu", () => {
      putSkillLink();
      const r = migratePi({ home, packageRoot: pkgRoot() });
      expect(r.skill.state).toBe("shim");
    });

    it("moves a copy byte-identical to a known release, never an edited one", () => {
      mkdirSync(join(skill(), "recipes"), { recursive: true });
      writeFileSync(join(skill(), "SKILL.md"), "---\nname: mu\n---\nrelease\n");
      writeFileSync(join(skill(), "recipes", "a.md"), "a\n");
      const known = [skillDirDigest(skill()) ?? ""];
      expect(known[0]).not.toBe("");
      expect(migratePi({ home, knownSkillDigests: known }).skill.state).toBe("shim");
      writeFileSync(join(skill(), "recipes", "a.md"), "edited\n");
      const r = migratePi({ home, apply: true, knownSkillDigests: known });
      expect(r.skill).toMatchObject({ state: "foreign", moved: false });
      expect(existsSync(join(skill(), "SKILL.md"))).toBe(true);
    });
  });

  it("is a no-op on an empty home", () => {
    const r = migratePi({ home, apply: true });
    expect(r.extension.state).toBe("absent");
    expect(r.skill.state).toBe("absent");
  });

  it("does not overwrite an earlier parked shim", () => {
    putShim();
    const first = migratePi({ home, apply: true }).extension.to;
    putShim();
    const second = migratePi({ home, apply: true }).extension.to;
    expect(second).not.toBe(first);
    expect(existsSync(first ?? "")).toBe(true);
  });
});

describe("upgrade guide", () => {
  it("installs the package, then migrates, then reloads", () => {
    const doc = readFileSync(join(root, "docs", "guide", "upgrade.md"), "utf8");
    const legacy = doc.slice(doc.indexOf("### Coming from the old"));
    const install = legacy.indexOf("pi install npm:@mu-crew/mu");
    const migrate = legacy.indexOf("mu pi migrate --apply");
    const reload = legacy.search(/restart|\/reload/);
    expect(install).toBeGreaterThan(-1);
    expect(migrate).toBeGreaterThan(install);
    expect(reload).toBeGreaterThan(migrate);
  });
});
